#!/usr/bin/env python3
"""Turn a desk statement into a complete Lean candidate using the lb_cert engine + lbgen.

usage: lbassemble.py ENGINE.lean MODULE STATEMENT_FILE OUT.lean [--maxstates N] [--chunks K] [--plain]
  ENGINE.lean: L_meta_7281.lean cut before its first data line (see extract_engine.py)
Exit codes: 0 written, 2 unsupported statement, 3 bound is false (circuit exists), 4 too big.
"""
import re, sys
import lbgen, lbparse

SRC_AUX = 'PEqualNP.Outside.L_meta_7281_aux'
HEADER = ['-- Lower-bound certificate checked by the frontier-search engine `lb_cert` of',
          '-- open-goat/pequalnp-proofs L_meta_7281 (Apache-2.0), reused unchanged. The certificate',
          '-- data below was generated by our own search (viche lbgen).']


def comments_to_dashes(text):
    """Strip all comments (block, doc, line) so the file stays on the desk's fast path."""
    text = re.sub(r'/-.*?-/', '', text, flags=re.S)
    out = []
    for line in text.split('\n'):
        if line.strip().startswith('--'):
            continue
        i = line.find(' --')
        if i >= 0:
            line = line[:i].rstrip()
        out.append(line)
    res = re.sub(r'\n{3,}', '\n\n', '\n'.join(out))
    return res


def main():
    eng_f, module, stmt_f, out_f = sys.argv[1:5]
    maxstates = int(sys.argv[sys.argv.index('--maxstates') + 1]) if '--maxstates' in sys.argv else 4000
    stmt = open(stmt_f).read().strip()
    c = lbparse.classify(stmt)
    if not c:
        print('unsupported statement shape', file=sys.stderr); sys.exit(2)
    kind, n, lb = c['kind'], c['n'], c['lb']
    try:
        y, how = lbparse.truth_table(n, c['fun'])
    except Exception as e:
        print('truth table failed:', e, file=sys.stderr); sys.exit(2)
    try:
        d = lbgen.gen_y(n, y, lb, maxstates=maxstates)
    except lbgen.Feasible:
        print('FALSE: a circuit with %d gates exists' % (lb - 1), file=sys.stderr); sys.exit(3)
    except lbgen.TooBig as e:
        print('too many states (> %s)' % e, file=sys.stderr); sys.exit(4)
    aux = module + '_aux'
    eng = open(eng_f).read().replace(SRC_AUX, aux)
    eng = comments_to_dashes(eng)
    eng = re.sub(r'(?m)^((?:private |protected )?)theorem\b', r'\1lemma', eng)
    if '"' in eng:
        print('engine contains double quotes', file=sys.stderr); sys.exit(2)
    lines = eng.split('\n')
    k = 0
    while k < len(lines) and lines[k].startswith('import '):
        k += 1
    lines = lines[:k] + [''] + HEADER + lines[k:]
    data, nparts = lbgen.emit_data_compact(d, chunks=int(sys.argv[sys.argv.index('--chunks')+1]) if '--chunks' in sys.argv else 6) if '--plain' not in sys.argv else lbgen.emit_data(d)
    proof = lbgen.emit_proof(d, nparts, module, stmt, aux)
    if kind == 'neg':
        proof[-1] = ('  exact fun h => absurd (lb_cert _ L_ M_ Y_ XS_ PD_ PM_ G_ T_cert %d %d rfl (by decide +kernel) '
                     '(by decide +kernel) (by decide +kernel) ⟨fun _ => false, fun _ => true, by decide⟩ '
                     '(by decide +kernel) (by decide +kernel) hT_cert (by decide +kernel) _ h) (by omega)'
                     % (d['cap'], d['lb']))
    text = '\n'.join(lines).rstrip('\n') + '\n\n' + '\n'.join(data) + '\n\n' + '\n'.join(proof) + '\n'
    open(out_f, 'w').write(text)
    print('wrote %s: %d bytes, %d states, |G|=%d' % (out_f, len(text.encode()), len(d['T']), len(d['G'])),
          file=sys.stderr)
    if len(text.encode()) > 524288:
        print('TOO LARGE for the desk (512 KiB)', file=sys.stderr); sys.exit(4)


if __name__ == '__main__':
    main()
