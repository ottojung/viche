"""Independent finite oracle for the bit-packing reflection family.

The Lean candidate generated by :mod:`bitpack` proves a finite identity between
a bit-packed ``word`` of a list of incident-row bitmasks and the packed row
labels.  This module re-implements that calculation from scratch in Python so a
candidate can be checked without running Lean.  Agreement is evidence for the
finite calculation only; it is not a kernel-check receipt and not desk credit.
"""
import random

DEFAULT_TRIALS = 400
DEFAULT_SEED = 20261128


def pack(bits):
    """List Bool -> Nat, exactly ``xs.foldr Nat.bit 0``."""
    out = 0
    for i, b in enumerate(bits):
        if b:
            out |= 1 << i
    return out


def flag(vector, n, diffs):
    """The incidence flag on one 2n-bit row (points then lines)."""
    return any(vector[n + line] and
               any(vector[(d + n - line) % n] for d in diffs)
               for line in range(n))


def word(masks, n, diffs):
    """``word`` on a list of 2n row-masks; bit k of the result is the k-th label."""
    out = 0
    for line in range(n):
        inner = 0
        for d in diffs:
            inner |= masks[(d + n - line) % n]
        out |= masks[n + line] & inner
    return out


def input_rows(rows, n):
    """``input`` on labelled rows: mask i collects bit i of every row vector."""
    return [sum(1 << k for k, (_, vec) in enumerate(rows) if vec[i])
            for i in range(2 * n)]


def verify_identity(n, diffs, trials=DEFAULT_TRIALS, seed=DEFAULT_SEED):
    """Check ``word (input rs) = pack (map Prod.fst rs)`` on random valid rows."""
    if n < 2 or not diffs or any(not (0 <= d < n) for d in diffs) or \
            len(set(diffs)) != len(diffs):
        return {"verified": False, "reason": "invalid parameters",
                "local_lean_checked": False}
    rng = random.Random(seed)
    for trial in range(trials):
        count = rng.randrange(0, 13)
        rows = []
        for _ in range(count):
            vec = [rng.random() < 0.45 for _ in range(2 * n)]
            rows.append((flag(vec, n, diffs), vec))
        got = word(input_rows(rows, n), n, diffs)
        expected = pack([label for label, _ in rows])
        if got != expected:
            return {"verified": False, "trial": trial, "n": n,
                    "diffs": list(diffs), "got": got, "expected": expected,
                    "local_lean_checked": False}
    return {"verified": True, "n": n, "diffs": list(diffs),
            "trials": trials, "seed": seed, "family": "bitpack_flag",
            "local_lean_checked": False}


def verify_generic_lemmas(n, diffs, trials=DEFAULT_TRIALS, seed=DEFAULT_SEED):
    """Independently re-check the exact finite lemmas the candidate reuses.

    Statements mirror the extracted upstream lemmas: readPack, foldOr, readMap,
    input_read and bitwise.  Only concrete finite instances are enumerated.
    """
    rng = random.Random(seed + 1)
    for _ in range(trials):
        xs = [rng.random() < 0.5 for _ in range(rng.randrange(0, 18))]
        k = rng.randrange(0, 20)
        # readPack: (pack xs).testBit k = xs.getD k false
        if bool(pack(xs) >> k & 1) != (xs[k] if k < len(xs) else False):
            return {"verified": False, "lemma": "readPack"}
        nums = [rng.randrange(0, 1 << 12) for _ in range(rng.randrange(0, 10))]
        a = rng.randrange(0, 1 << 12)
        folded = 0
        for x in nums:
            folded |= x
        folded |= a
        # foldOr: testBit(foldl (·|||·) a xs) k = a.testBit k || xs.any (·.testBit k)
        lhs = bool(folded >> k & 1)
        rhs = bool(a >> k & 1) or any(x >> k & 1 for x in nums)
        if lhs != rhs:
            return {"verified": False, "lemma": "foldOr"}
        rows = []
        for _ in range(rng.randrange(0, 10)):
            vec = [rng.random() < 0.45 for _ in range(2 * n)]
            rows.append((rng.random() < 0.5, vec))
        j = rng.randrange(0, 2 * n)
        kk = rng.randrange(0, max(1, len(rows) + 3))
        # input_read: bit k of mask j equals bit j of row k (or false if absent)
        row_vec = rows[kk][1] if kk < len(rows) else ([False] * (2 * n))
        if bool(input_rows(rows, n)[j] >> kk & 1) != row_vec[j]:
            return {"verified": False, "lemma": "input_read"}
        kk2 = rng.randrange(0, max(1, len(rows) + 3))
        row2 = rows[kk2][1] if kk2 < len(rows) else ([False] * (2 * n))
        # bitwise: bit k of word(input rs) = flag(row k)
        if bool(word(input_rows(rows, n), n, diffs) >> kk2 & 1) != \
                flag(row2, n, diffs):
            return {"verified": False, "lemma": "bitwise"}
    return {"verified": True, "trials": trials, "seed": seed + 1,
            "lemmas": ["readPack", "foldOr", "readMap", "input_read", "bitwise"],
            "local_lean_checked": False}
